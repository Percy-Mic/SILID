const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ headless: true });
  const p = await b.newPage({ viewport: { width: 1024, height: 600 } });
  const errs=[]; p.on('pageerror', e=>errs.push('PAGEERROR '+e.message));
  await p.goto('http://127.0.0.1:5333/?probe=1');
  await p.waitForFunction(() => window.__silid?.ready, null, { timeout: 120000 });
  const read=()=>p.evaluate(()=>{const s=window.__silid;return{x:+s.player.pos.x.toFixed(2),z:+s.player.pos.z.toFixed(2),foot:+s.player.footY.toFixed(2),room:document.getElementById('room').textContent,level:document.getElementById('level').textContent,prompt:document.getElementById('prompt').textContent,msg:document.getElementById('msg').textContent,powered:s.game.state.powered,inv:[...s.game.inventory]};});
  const out={};
  await p.evaluate(()=>window.__silid.spawnAt(0,12.9,0,0,0));
  await p.waitForTimeout(500); out.prompt=(await read()).prompt;
  await p.keyboard.press('KeyE'); await p.waitForTimeout(600);
  await p.keyboard.down('w'); await p.waitForTimeout(7000); await p.keyboard.up('w');
  out.walkIn=await read();
  await p.evaluate(()=>window.__silid.spawnAt(10.5,-0.6,-3.0,Math.PI,-0.15));
  await p.waitForTimeout(700); out.fusePrompt=(await read()).prompt;
  await p.keyboard.press('KeyE'); await p.waitForTimeout(500); out.fuse=await read();
  await p.evaluate(()=>window.__silid.spawnAt(2.2,-6.6,-3.4,Math.PI/2,-0.1));
  await p.waitForTimeout(700); out.fuelPrompt=(await read()).prompt;
  await p.keyboard.press('KeyE'); await p.waitForTimeout(500); out.fuel=await read();
  await p.evaluate(()=>window.__silid.spawnAt(3.0,-3.6,-3.4,0,-0.05));
  await p.waitForTimeout(700); out.genPrompt=(await read()).prompt;
  await p.keyboard.press('KeyE'); await p.waitForTimeout(1200); out.gen=await read();
  await p.evaluate(()=>window.__silid.spawnAt(-13.4,20,null,0,0));
  await p.waitForTimeout(700); out.gatePrompt=(await read()).prompt;
  await p.keyboard.press('KeyE'); await p.waitForTimeout(4500);
  out.gate=await read(); out.ended=await p.evaluate(()=>window.__silid.game.state.ended);
  out.errors=errs;
  console.log(JSON.stringify(out,null,1));
  await b.close();
})();
